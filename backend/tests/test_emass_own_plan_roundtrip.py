def test_repro_both_paths(client, ctx):
    """Root cause (before the fix): every row got a required-field issue, bulk accept skipped them and apply saved nothing."""
    data = FX.read_bytes()
    d = er.detect(er.read_sheets(data, FX.name))
    assert d["type"] == "control_information" and d["confidence"] == "high"
    r = client.post(f"/api/v1/systems/{ctx['sid']}/emass-imports", files={"file": (FX.name, data)}, headers=ctx["isso"])
    assert r.status_code == 201, r.text
    p1 = r.json()
    assert p1["detection"]["sheet"] == "Implementation Plan" and p1["detection"]["header_row"] == 2
    r = client.post("/api/v1/emass-imports", files={"file": (FX.name, data)}, data={"system_id": ctx["sid"]}, headers=ctx["isso"])
    assert r.status_code == 201
    r2 = client.post(f"/api/v1/emass-imports/{r.json()['id']}/target", json={"action": "update", "system_id": ctx["sid"]}, headers=ctx["isso"])
    assert r2.status_code == 200
    for j in (p1, r2.json()):
        s = j["report"]["summary"]
        print("SUMMARY", s, {k: len(j["report"][k]) for k in ("warnings", "info", "status_not_applied", "required_issues", "invalid", "blocked")})
        assert s["rows_read"] == 423 and s["rows_to_apply"] == 287 and s["rows_with_errors"] == 0
        assert s["rows_not_in_system"] == 136 and s["placeholders_ignored"] == 287
        assert sum(1 for w in j["report"]["warnings"] if w["field"] == "Common Control Provider") == 287, "CCP on non-inherited rows → warning, not applied"
        assert sum(1 for w in j["report"]["warnings"] if w["field"] == "Implementation Status") == len(j["report"]["status_not_applied"]) > 0
        assert all("common_control_provider" not in i["fields"] and "na_justification" not in i["fields"] for i in j["items"])
    ctx["p1"] = p1


def test_status_gate_uses_resolved_slcm_from_approved_strategy(client, ctx):
    """Required-field check uses the same resolver as exports / missing-fields filter: approved strategy SLCM counts."""
    import io

    from openpyxl import Workbook

    from app.models import IscmStrategy
    from app.services import emass_fields as ef
    sid = client.post("/api/v1/systems", json={"name": "Strategy Target", "acronym": "STR" + uuid.uuid4().hex[:3], **FIPS}, headers=ctx["isso"]).json()["id"]
    slcm = {"slcm_criticality": "CRWG White Criticality Control", "slcm_frequency": "Monthly", "slcm_method": "Automated",
            "slcm_reporting": "ISSO to ISSM", "slcm_tracking": "POA&M", "slcm_comments": "SYNTHETIC"}
    assert set(slcm) == set(ef.SLCM)
    with SessionLocal() as db:
        db.add(IscmStrategy(system_id=uuid.UUID(sid), status="approved", defaults=slcm, approved_snapshot={"defaults": slcm, "profiles": []}))
        db.commit()
    wb = Workbook()
    ws = wb.active
    ws.title = "Implementation Plan"
    ws.append(["eMASS-formatted, compatibility pending human verification – generated by IronVision AI"])
    ws.append(["Control Acronym", "Implementation Status", "Security Control Designation", "Estimated Completion Date", "Responsible Entities", "Common Control Provider"])
    ws.append(["AC-2", "Implemented ", "System-Specific", "2026-12-31", "ISSO", "N/A "])
    ws.append(["AC-3", "Implemented", "Hybrid", None, None, "-"])
    b = io.BytesIO()
    wb.save(b)
    r = client.post(f"/api/v1/systems/{sid}/emass-imports", files={"file": ("plan.xlsx", b.getvalue())}, headers=ctx["isso"])
    assert r.status_code == 201, r.text
    j = r.json()
    items = {i["control_id"]: i for i in j["items"]}
    assert not items["ac-2"]["fields"]["implementation_status"]["blocked"], "SLCM comes from the approved strategy – Implemented applies"
    msg = items["ac-3"]["fields"]["implementation_status"]["blocked"]
    assert msg.startswith("Implemented not applied – missing: Estimated Completion Date, Responsible Entities (add them to the file")
    assert "SLCM" not in msg and j["report"]["summary"]["placeholders_ignored"] == 2
    u = f"/api/v1/systems/{sid}/emass-imports/{j['id']}"
    client.put(f"{u}/decisions", json={"bulk": "accept_safe"}, headers=ctx["isso"])
    assert client.post(f"{u}/apply", headers=ctx["isso"]).json()["counts"]["failed_controls"] == 0
    assert client.get(f"/api/v1/systems/{sid}/workbench/controls/ac-2/emass", headers=ctx["isso"]).json()["implementation_status"] == "Implemented"
    assert client.get(f"/api/v1/systems/{sid}/workbench/controls/ac-3/emass", headers=ctx["isso"]).json()["implementation_status"] != "Implemented"


def test_apply_changes_target_fields_with_audit(client, ctx):
    p1 = ctx["p1"]
    u = f"/api/v1/systems/{ctx['sid']}/emass-imports/{p1['id']}"
    d = client.put(f"{u}/decisions", json={"bulk": "accept_safe"}, headers=ctx["isso"]).json()
    assert d["counts"]["accepted"] >= 287
    r = client.post(f"{u}/apply", headers=ctx["isso"])
    assert r.status_code == 200, r.text
    res = {x["control"]: x for x in r.json()["results"]}
    assert res["AC-2"]["applied"] and not res["AC-2"]["failed"] and res["AC-2"]["warning"]
    assert r.json()["counts"]["failed_controls"] == 0
    with SessionLocal() as db:
        a = db.scalar(select(ControlAssignment).where(ControlAssignment.system_id == uuid.UUID(ctx["sid"]), ControlAssignment.control_id == "ac-2"))
        f = db.scalar(select(EmassControlFields).where(EmassControlFields.assignment_id == a.id))
        assert f.control_designation == "System-Specific" and f.common_control_provider is None and f.na_justification is None
        ev = db.scalar(select(AuditEvent).where(AuditEvent.entity_id == str(a.id), AuditEvent.action == "emass.plan_updated"))
        assert ev.after["control_designation"] == "System-Specific" and ev.details["import_id"] == p1["id"]

