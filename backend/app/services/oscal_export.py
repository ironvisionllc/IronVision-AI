def _pattern(validator, patrn, instance, schema):
    if validator.is_type(instance, "string") and not regex.search(patrn, instance):
        yield ValidationError(f"{instance!r} does not match {patrn!r}")


OscalValidator = validators.extend(Draft7Validator, {"pattern": _pattern})


def schema_dir() -> Path:
    return Path(get_settings().content_dir) / "oscal-schemas" / f"v{OSCAL_VERSION}"


@lru_cache
def _schema(model: str) -> tuple[dict, str]:
    entry = json.loads((Path(get_settings().content_dir) / "manifest.json").read_text())["oscal_schemas"]
    f = MODELS[model][1]
    raw = (schema_dir() / f).read_bytes()
    sha = hashlib.sha256(raw).hexdigest()
    if sha != entry["files"][f]["sha256"]:
        raise RuntimeError(f"OSCAL schema hash mismatch: {f}")
    return json.loads(raw), sha


def validate(model: str, doc: dict) -> dict:
    schema, sha = _schema(model)
    errs = sorted(OscalValidator(schema, format_checker=Draft7Validator.FORMAT_CHECKER).iter_errors(doc), key=lambda e: list(e.absolute_path))
    return {"valid": not errs, "error_count": len(errs), "schema": MODELS[model][1], "schema_sha256": sha, "oscal_version": OSCAL_VERSION,
            "validator": "jsonschema Draft-07 (regex engine for \\p{..} patterns)",
            "errors": [{"path": "/".join(map(str, e.absolute_path)), "message": e.message[:300]} for e in errs[:50]]}


def _ts(d=None) -> str:
    return (d or datetime.now(timezone.utc)).astimezone(timezone.utc).isoformat(timespec="seconds")


def _u(*parts) -> str:
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "aegisrmf:" + ":".join(map(str, parts))))


def _meta(s: System, title: str) -> dict:
    return {"title": f"{title} – {s.name} ({s.acronym}) – SYNTHETIC", "last-modified": _ts(), "version": datetime.now(timezone.utc).strftime("%Y%m%d%H%M%S"),
            "oscal-version": OSCAL_VERSION, "remarks": "Generated by IronVision AI from synthetic demonstration data."}


def _sysid(s: System) -> dict:
    return {"identifier-type": "https://ietf.org/rfc/rfc4122", "id": str(s.id)}


def build_poam(db: Session, s: System) -> dict:
    obs, risks, items = [], [], []
    for p in db.scalars(select(Poam).where(Poam.system_id == s.id).order_by(Poam.seq)):
        fids = [f for (f,) in db.execute(select(PoamFinding.finding_id).where(PoamFinding.poam_id == p.id))]
        o_ids = []
        for f in db.scalars(select(Finding).where(Finding.id.in_(fids))) if fids else []:
            ou = _u("obs", f.id)
            o_ids.append({"observation-uuid": ou})
            obs.append({"uuid": ou, "title": (f.vuln_id or f.plugin_id or "finding") + " " + f.title[:200], "description": f.title,
                        "methods": ["TEST"], "collected": _ts(f.last_seen_at)})
        ru = _u("risk", p.id)
        status = "closed" if p.status in ("closed",) else "deviation-approved" if p.status == "risk_accepted" else "open"
        risk = {"uuid": ru, "title": p.weakness[:250], "description": p.security_impact or p.weakness, "statement": p.remediation_plan or "Remediation plan pending.",
                "status": status, "props": [{"name": "aegis-cat", "ns": "https://aegisrmf.demo/ns/oscal", "value": p.cat or "none"}]}
        if p.due_date:
            risk["deadline"] = _ts(datetime.combine(p.due_date, datetime.min.time(), timezone.utc))
        if o_ids:
            risk["related-observations"] = o_ids
        risks.append(risk)
        item = {"uuid": str(p.id), "title": f"{p.human_id}: {p.weakness[:240]}", "description": p.weakness,
                "props": [{"name": "POAM-ID", "value": p.human_id}], "related-risks": [{"risk-uuid": ru}]}
        if o_ids:
            item["related-observations"] = o_ids
        items.append(item)
    body = {"uuid": _u("poam", s.id, datetime.now(timezone.utc).isoformat()), "metadata": _meta(s, "Plan of Action and Milestones"),
            "system-id": _sysid(s), "poam-items": items or [{"uuid": _u("empty", s.id), "title": "No POA&M items", "description": "No open items"}]}
    if obs:
        body["observations"] = obs
    if risks:
        body["risks"] = risks
    return {"plan-of-action-and-milestones": body}


def _level(v):
    return {"low": "fips-199-low", "moderate": "fips-199-moderate", "high": "fips-199-high"}.get((v or "").lower(), "fips-199-moderate")


def build_ssp(db: Session, s: System) -> dict:
    comp = _u("this-system", s.id)
    narr = {aid: n for aid, n in db.execute(select(Implementation.assignment_id, Implementation.narrative).join(
        ControlAssignment, ControlAssignment.id == Implementation.assignment_id).where(ControlAssignment.system_id == s.id, Implementation.is_current.is_(True)))}
    reqs = []
    from app.models import EmassControlFields
    from app.services import emass_fields as ef

    fmap = {f.assignment_id: f for f in db.scalars(select(EmassControlFields).where(EmassControlFields.system_id == s.id))}
    from app.services import iscm
    res = iscm.resolver(db, s)
    for a in db.scalars(select(ControlAssignment).where(ControlAssignment.system_id == s.id).order_by(ControlAssignment.control_id)):
        eprops, eremarks = ef.oscal_props(fmap.get(a.id), a, ef.effective(db, a, fmap.get(a.id), res)[0])
        req = {"uuid": str(a.id), "control-id": a.control_id,
               "props": [{"name": "implementation-status", "value": "implemented" if a.implementation_status == "implemented" else "planned"},
                         {"name": "control-origination", "ns": "https://aegisrmf.demo/ns/oscal", "value": a.responsibility}, *eprops],
               "by-components": [{"component-uuid": comp, "uuid": _u("byc", a.id),
                                  "description": (narr.get(a.id) or "").strip() or "No statement recorded."}]}
        if eremarks:
            req["remarks"] = eremarks
        reqs.append(req)
    comps = [{"uuid": comp, "type": "this-system", "title": s.name, "description": s.description or s.name, "status": {"state": "operational"}}]
    for x in db.scalars(select(Asset).where(Asset.system_id == s.id).limit(200)):
        comps.append({"uuid": str(x.id), "type": "hardware" if (x.asset_type or "") in ("server", "host", "") else "software", "title": x.name,
                      "description": f"{x.asset_type or 'asset'} {x.os or ''} {x.ip_address or ''}".strip(), "status": {"state": "operational"}})
    sc = {"system-ids": [_sysid(s)], "system-name": s.name, "system-name-short": s.acronym or s.name, "description": s.description or s.name,
          "security-sensitivity-level": _level(s.categorization),
          "system-information": {"information-types": [{"uuid": _u("it", s.id), "title": "System information (synthetic)",
                                                        "description": "Categorization recorded in IronVision AI.",
                                                        "confidentiality-impact": {"base": _level(s.confidentiality_impact)},
                                                        "integrity-impact": {"base": _level(s.integrity_impact)},
                                                        "availability-impact": {"base": _level(s.availability_impact)}}]},
          "security-impact-level": {"security-objective-confidentiality": _level(s.confidentiality_impact),
                                    "security-objective-integrity": _level(s.integrity_impact),
                                    "security-objective-availability": _level(s.availability_impact)},
          "status": {"state": "operational" if (s.lifecycle_phase or "").lower() in ("operate", "operations") else "under-development"},
          "authorization-boundary": {"description": s.boundary_description or "Boundary described in the system record (synthetic)."}}
    return {"system-security-plan": {
        "uuid": _u("ssp", s.id, datetime.now(timezone.utc).isoformat()), "metadata": _meta(s, "System Security Plan"),
        "import-profile": {"href": f"https://raw.githubusercontent.com/usnistgov/oscal-content/main/nist.gov/SP800-53/rev5/json/NIST_SP-800-53_rev5_{(s.baseline_key or 'moderate').upper()}-baseline_profile.json"},
        "system-characteristics": sc,
        "system-implementation": {"users": [{"uuid": _u("user", s.id, "isso"), "title": "Information System Security Officer", "role-ids": ["isso"]}],
                                  "components": comps},
        "control-implementation": {"description": f"Controls assigned from the {s.baseline_key} baseline plus tailoring.", "implemented-requirements": reqs}}}


def _assessed(db: Session, s: System) -> list[Assessment]:
    return list(db.scalars(select(Assessment).where(Assessment.system_id == s.id).order_by(Assessment.created_at)))


def _selection(ctrls) -> dict:
    ctrls = sorted(set(ctrls))
    return {"control-selections": [{"include-controls": [{"control-id": c} for c in ctrls]} if ctrls else {"include-all": {}}]}


def build_ap(db: Session, s: System) -> dict:
    ctrls = [a.control_id for a in db.scalars(select(ControlAssignment).where(ControlAssignment.system_id == s.id))]
    return {"assessment-plan": {"uuid": _u("ap", s.id, datetime.now(timezone.utc).isoformat()), "metadata": _meta(s, "Security Assessment Plan"),
                                "import-ssp": {"href": f"#ssp-{s.id}"}, "reviewed-controls": _selection(ctrls)}}


def build_ar(db: Session, s: System) -> dict:
    ass = _assessed(db, s)
    findings, obs = [], []
    for a in ass:
        ou = _u("ar-obs", a.id)
        obs.append({"uuid": ou, "description": a.findings_text or f"SCA assessment of {a.control_id}",
                    "methods": [m.upper() for m in a.methods if m.upper() in ("EXAMINE", "INTERVIEW", "TEST")] or ["EXAMINE"], "collected": _ts(a.created_at)})
        findings.append({"uuid": str(a.id), "title": f"{fmt_control(a.control_id)} assessment", "description": a.findings_text or a.result,
                         "target": {"type": "objective-id", "target-id": f"{a.control_id}_obj",
                                    "status": {"state": "satisfied" if a.result == "satisfied" else "not-satisfied"}},
                         "related-observations": [{"observation-uuid": ou}]})
    res = {"uuid": _u("ar-res", s.id, datetime.now(timezone.utc).isoformat()), "title": f"Assessment results for {s.acronym}",
           "description": "SCA assessment results recorded in IronVision AI (SYNTHETIC).", "start": _ts(ass[0].created_at if ass else None),
           "reviewed-controls": _selection([a.control_id for a in ass])}
    if obs:
        res["observations"], res["findings"] = obs, findings
    return {"assessment-results": {"uuid": _u("ar", s.id, datetime.now(timezone.utc).isoformat()), "metadata": _meta(s, "Security Assessment Results"),
                                   "import-ap": {"href": f"#ap-{s.id}"}, "results": [res]}}


BUILDERS = {"poam": build_poam, "ssp": build_ssp, "assessment-plan": build_ap, "assessment-results": build_ar}


def export(db: Session, s: System, model: str, actor_email: str) -> dict:
    from app.services import audit
    from app.services.rmf import store_evidence

    doc = BUILDERS[model](db, s)
    result = validate(model, doc)
    raw = json.dumps(doc, indent=2).encode()
    name = f"{s.acronym or 'system'}_oscal_{model}_{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S')}{'' if result['valid'] else '_INVALID'}.json"
    ev = store_evidence(db, s.id, name, raw, "oscal_export", actor_email, "oscal_export")
    ev.provenance = {**(ev.provenance or {}), "oscal_model": model, "validation": {k: v for k, v in result.items() if k != "errors"},
                     "validation_errors": result["errors"][:10]}
    audit.record(db, action="oscal.exported", actor_email=actor_email, entity_type="evidence", entity_id=str(ev.id),
                 details={"model": model, "system_id": str(s.id), "valid": result["valid"], "errors": result["error_count"], "sha256": ev.sha256})
    return {"evidence_id": str(ev.id), "sha256": ev.sha256, "file_name": name, "validation": result,
            "label": "Valid OSCAL (schema-validated)" if result["valid"] else "NOT valid OSCAL – schema validation failed", "document": doc}
