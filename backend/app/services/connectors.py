class ConnectorAdapter:
    mode = "file_import"

    def test_connection(self, source: EvidenceSource) -> tuple[bool, str]:
        return True, "File import only – no network connection is made. Upload exported files for this source."

    def collect(self, db: Session, source: EvidenceSource, actor_id=None) -> dict:
        return {"collected": 0, "message": "File import only – upload a file to ingest evidence."}


class MockAdapter(ConnectorAdapter):
    mode = "mock"

    def test_connection(self, source: EvidenceSource) -> tuple[bool, str]:
        return True, "MOCK/DEMO adapter – no external system was contacted. A real connector is not yet implemented."

    def collect(self, db: Session, source: EvidenceSource, actor_id=None) -> dict:
        ts = datetime.now(timezone.utc)
        doc = {"SYNTHETIC_MOCK_COLLECTION": True, "source": source.name, "source_type": source.source_type,
               "collected_at": ts.isoformat(), "controls": (source.config or {}).get("control_ids", []),
               "note": "Generated by the MOCK/DEMO adapter. Not real system evidence."}
        raw = json.dumps(doc, indent=2).encode()
        sha = hashlib.sha256(raw).hexdigest()
        key = f"evidence/{source.system_id}/{sha}/mock-{source.source_type}.json"
        get_storage().put(key, raw, "application/json")
        ev = Evidence(id=uuid.uuid4(), system_id=source.system_id, source_id=source.id, name=f"{source.name} – mock collection",
                      evidence_type=EVIDENCE_TYPE.get(source.source_type, "manual"), file_name=key.rsplit("/", 1)[1],
                      storage_key=key, sha256=sha, size_bytes=len(raw), content_type="application/json", collected_at=ts,
                      integrity_status="verified", last_verified_at=ts, state="current", source="mock_adapter",
                      provenance={"adapter": "mock", "synthetic": True})
        db.add(ev)
        db.flush()
        linked = 0
        for a in db.scalars(select(ControlAssignment).where(ControlAssignment.system_id == source.system_id,
                                                            ControlAssignment.control_id.in_(doc["controls"]))):
            db.add(EvidenceControl(evidence_id=ev.id, assignment_id=a.id))
            linked += 1
        hosts = (source.config or {}).get("hosts") or ([{"host": "mock-onprem-01", "ip": "198.51.100.10"}] if source.source_type == "on_prem" else [])
        for h in hosts:  # MOCKED host report – a scan-only asset labelled "mock:…", never shown as verified discovery
            from app.models import Asset, AssetCorrelation
            from app.services.inventory import correlate as cr
            obs = cr.observed({"host": h["host"], "ips": [h["ip"]]})
            if db.scalar(select(AssetCorrelation).where(AssetCorrelation.system_id == source.system_id, AssetCorrelation.key == cr.facts_key(obs))):
                continue
            a = Asset(system_id=source.system_id, name=h["host"], hostname=cr.n_host(h["host"]), ip_address=h["ip"], ip_addresses=[h["ip"]], asset_type="unknown",
                      inventory_source=f"mock:{source.source_type}", is_unmatched=True, review_status="needs_review", source="mock_adapter",
                      provenance={"adapter": "mock", "synthetic": True, "evidence_id": str(ev.id)})
            db.add(a)
            db.flush()
            db.add(AssetCorrelation(system_id=source.system_id, key=cr.facts_key(obs), facts={"host": h["host"], "ips": [h["ip"]], "mocked": True}, candidates=[],
                                    status="new", reason="MOCKED connector host report", observed_asset_id=a.id, source_format="mock_json", evidence_ids=[str(ev.id)],
                                    last_seen_at=ts))
        db.add(IngestRun(system_id=source.system_id, source_id=source.id, evidence_id=ev.id, file_name=ev.file_name,
                         file_format="mock_json", sha256=sha, status="completed", finished_at=ts, total=1,
                         mapped=1 if linked else 0, controls_touched=linked, requested_by=actor_id,
                         stats={"mock": True, "linked_controls": linked}))
        db.flush()
        audit.record(db, action="source.collected", actor_user_id=actor_id, entity_type="evidence_source", entity_id=str(source.id),
                     details={"adapter": "mock", "evidence_id": str(ev.id), "linked_controls": linked})
        return {"collected": 1, "linked_controls": linked, "message": "MOCK/DEMO collection produced one synthetic evidence item."}


def adapter_for(source_type: str) -> ConnectorAdapter:
    return MockAdapter() if SOURCE_TYPES[source_type][1] == "mock" else ConnectorAdapter()
