"""Generate the SYNTHETIC 'Demo OS STIG' releases (AegisRMF JSON content format) and pin them in content/manifest.json.

V1R1 (July) is installed by the seed. V1R2 (October) is available, with 6 rules added, 3 removed, 11 changed requirements
and 2 severity changes. V-900118 (behind P-0027) goes from medium to high, i.e. CAT II to CAT I.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "backend" / "content" / "stig" / "demo-linux-server"
BENCH = "Demo Linux Server STIG (SYNTHETIC)"

BASE = [
    ("V-900101", "medium", "The SSH daemon must not permit direct root logins.", ["CCI-000366", "CCI-000770"]),
    ("V-900118", "medium", "Audit log files must have mode 0600 or less permissive.", ["CCI-000162", "CCI-000163", "CCI-000164"]),
    ("V-900140", "high", "The operating system must enable FIPS 140-validated cryptography (FIPS mode).", ["CCI-002450", "CCI-000366", "CCI-000068"]),
    ("V-900200", "medium", "The system must display the Standard Mandatory Notice and Consent Banner.", ["CCI-000048"]),
    ("V-900210", "low", "The system must limit the number of concurrent sessions.", ["CCI-000054"]),
    ("V-900220", "medium", "Audit records must contain event type information.", ["CCI-000130"]),
    ("V-900999", "low", "Legacy policy documentation check (CCI has no Rev 5 reference – expected UNMAPPED).", ["CCI-000001"]),
]
EXTRA_CCIS = ["CCI-000044", "CCI-000057", "CCI-000381", "CCI-000185", "CCI-000192", "CCI-001314", "CCI-000172", "CCI-001499", "CCI-002165"]
EXTRAS = [(f"V-9{230 + i * 10:05d}"[:2] + f"{900230 + i * 10}"[0:0] or f"V-{900230 + i * 10}", ["low", "medium", "medium"][i % 3],
           f"Demo OS hardening requirement #{i + 1}: the system must enforce configuration setting {i + 1} (SYNTHETIC).",
           [EXTRA_CCIS[i % len(EXTRA_CCIS)]]) for i in range(18)]
EXTRAS = [(f"V-{900230 + i * 10}", sev, title, ccis) for i, (_, sev, title, ccis) in enumerate(EXTRAS)]

REMOVED = {"V-900999", "V-900390", "V-900400"}
REWORDED = {"V-900101", "V-900200", "V-900220", "V-900230", "V-900240", "V-900250", "V-900260", "V-900270", "V-900280", "V-900290", "V-900300"}
SEVERITY = {"V-900118": "high", "V-900210": "medium"}
ADDED = [(f"V-{900410 + i * 10}", ["medium", "high", "low", "medium", "medium", "low"][i],
          f"New in V1R2: the system must enable control {i + 1} of the updated hardening guidance (SYNTHETIC).", [EXTRA_CCIS[(i + 3) % 9]])
         for i in range(6)]


def rule(vid, sev, title, ccis, rel, reworded=False):
    n = vid.split("-")[1]
    return {"vuln_id": vid, "rule_id": f"SV-{n}r{rel}_rule", "severity": sev, "title": title, "ccis": ccis,
            "check_text": f"Verify: {title}" + (" Additionally verify the setting persists across reboot (V1R2 wording)." if reworded else ""),
            "fix_text": f"Configure the system so that: {title}"}


def release(version, release_no, date, rules):
    return {"format": "aegisrmf-stig-json/1", "synthetic": True, "benchmark": BENCH, "benchmark_key": "demo-linux-server",
            "title": f"Demo OS STIG {version} (SYNTHETIC – not a DISA publication)", "version": version, "release": release_no,
            "release_date": date, "source": "Synthetic demo content generated by scripts/generate_stig_content.py", "rules": rules}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    r1 = [rule(*x, 1) for x in BASE + EXTRAS]
    r2 = []
    for x in BASE + EXTRAS:
        vid, sev, title, ccis = x
        if vid in REMOVED:
            continue
        if vid in REWORDED:
            r2.append(rule(vid, sev, title.rstrip(".") + ", including after system restart.", ccis, 2, True))
        else:
            r2.append(rule(vid, SEVERITY.get(vid, sev), title, ccis, 1 if vid not in SEVERITY else 2))
    r2 += [rule(*x, 1) for x in ADDED]
    manifest_path = ROOT / "backend" / "content" / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    entries = []
    for ver, rel, date, rules, status in (("V1R1", 1, "2026-07-24", r1, "installed"), ("V1R2", 2, "2026-10-23", r2, "available")):
        raw = json.dumps(release(ver, rel, date, rules), indent=1).encode()
        (OUT / f"{ver}.json").write_bytes(raw)
        entries.append({"key": "demo-linux-server", "version": ver, "effective_date": date, "seed_status": status,
                        "path": f"stig/demo-linux-server/{ver}.json", "sha256": hashlib.sha256(raw).hexdigest(),
                        "title": f"Demo OS STIG {ver} (SYNTHETIC)", "benchmark": BENCH,
                        "source_url": "synthetic://aegisrmf/scripts/generate_stig_content.py"})
    manifest["stig"] = entries
    manifest_path.write_text(json.dumps(manifest, indent=1) + "\n")
    print({e["version"]: e["sha256"][:12] for e in entries}, len(r1), len(r2))


if __name__ == "__main__":
    main()
