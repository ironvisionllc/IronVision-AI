SLATE_DARK = ["#172033", "#1f2a3e", "#334155", "#6b7a90", "#8b98ad", "#94A3B8", "#a8b4c6", "#CBD5E1", "#e2e8f0", "#f1f5f9", "#f8fafc"]
SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]
DARK_BASE = (30, 41, 59)


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def blend(h, a):
    c = rgb(h)
    return tuple(round(a * c[i] + (1 - a) * DARK_BASE[i]) for i in range(3))


def dark_scale(s):
    tint = [blend(s[5], a) for a in (0.14, 0.22, 0.34, 0.55)]
    return tint + [rgb(s[4]), rgb(s[5]), rgb(s[5]), rgb(s[3]), rgb(s[2]), rgb(s[1]), rgb(s[0])]


def trip(t):
    return f"{t[0]} {t[1]} {t[2]}"


light, dark = [], []
for fam, s in SCALES.items():
    d = [rgb(x) for x in SLATE_DARK] if fam == "slate" else dark_scale(s)
    for i, sh in enumerate(SHADES):
        light.append(f"  --c-{fam}-{sh}: {trip(rgb(s[i]))};")
        dark.append(f"  --c-{fam}-{sh}: {trip(d[i])};")
    for i, sh in enumerate(SHADES):
        light.append(f"  --iv-{fam}-{sh}: {s[i]};")  # fixed (non-theming) brand/accent hex values

