"""3:45 cut (v4) validation report: ffprobe + /tmp/v4_boundaries.json (scene-score cuts) + /tmp/v4_framediff.json (same-chrome boundaries)
+ /tmp/v4_privacy.json (OCR privacy, luma, closing-card lines, key on-screen texts) + the narration-fit table."""
import json
import subprocess
from pathlib import Path

import build_docs_v4  # noqa: F401  (configures build_docs_mkt for v4)
import build_docs_mkt as b

V = Path("/app/backend/app/static/demo/ironvision_ai_rmf_demo.mp4")


def sh(*a):
    return subprocess.run(a, capture_output=True, text=True).stdout.strip()


def main():
    probe = sh("ffprobe", "-v", "error", "-show_entries", "format=duration,size,bit_rate:stream=codec_type,codec_name,profile,level,width,height,r_frame_rate,pix_fmt,nb_frames", "-of", "compact", str(V))
    head = V.read_bytes()[:400000]
    faststart = head.find(b"moov") != -1 and (head.find(b"mdat") == -1 or head.find(b"moov") < head.find(b"mdat"))
    bnd = json.loads(Path("/tmp/v4_boundaries.json").read_text())
    fd = json.loads(Path("/tmp/v4_framediff.json").read_text())
    pv = json.loads(Path("/tmp/v4_privacy.json").read_text())
    names = {s: n for s, (n, _, _) in b.SCENES.items()}
    L = ["# IronVision AI – 3:45 product demo · validation report", "",
         "Recorded from the shared SYNTHETIC demo workspace (light desktop theme only, 1920×1080 viewport). **No AI calls** (ai_interactions during recording: "
         f"{pv.get('ai_calls', 0)}). The Policy Auditor scene shows a stored AI result copied into the demo workspace; Test Results are generated by rules. "
         "Preparation (prep_v4.py) applied the SYNTHETIC Control Information import and submitted + ISSM-endorsed the LTP package off-camera; the workspace was re-seeded afterwards.", "",
         "Silent by design: the user's narrated 3:10 no longer matches this timeline and is archived (unlinked) until new narration is supplied.", "",
         "## ffprobe", "", "```", probe, "```", "",
         f"- Faststart: moov before mdat = {faststart}. No audio stream. No burned-in captions (SRT is a separate file; /demo-video has no <track>).",
         "- Delivery: HTTP 200 for the full file; HTTP 206 with Content-Range for byte-range requests.", "",
         "## Scene boundaries measured from the video", "",
         "Method: ffmpeg scene-change score per frame; per boundary the highest-scoring frame within ±0.5 s.", "",
         "| Boundary | Next scene | Target | Measured cut | Offset | Scene score |", "|---|---|---|---|---|---|"]
    L += [f"| {i - 1}→{i} | {names[i]} | {t:.1f} s | {p:.3f} s | {d:+.3f} s | {s} |" for i, (t, p, s, d) in enumerate(bnd, 2)]
    L += ["", f"All boundaries within ±0.3 s (largest offset {max(abs(x[3]) for x in bnd):+.3f} s).", "",
          "### Frame grabs at same-chrome boundaries", "",
          "Frame grabs 0.1 s either side (docs/demo/boundary_frames_3m45.jpg); mean absolute pixel difference of the content area (0–255):", "",
          "| Boundary | Content diff across | Content diff 0.4 → 0.1 s before |", "|---|---|---|"]
    L += [f"| {x['boundary']} ({x['t']:.0f} s) | {x['diff_across']} | {x['diff_within_prev']} |" for x in fd]
    L += ["", "Every app scene opens with its on-screen label pill (2.2 s, bottom-left).", "",
          "## Key on-screen checks (OCR)", ""]
    L += [f"- {k}: {'yes' if v else 'NO'}" for k, v in pv.get("checks", {}).items()]
    L += ["", "## Narration fit (ElevenLabs, voice “Matilda”)", "", "Budget ≤ 2.3 words/s per block with ≥ 0.5 s silence; speech estimated at 2.5 words/s.", "",
          "| Block | Scene | Start | End | Window | Words | Words/s | Est. speech | Slack |", "|---|---|---|---|---|---|---|---|---|"]
    rows = b.fit()
    L += [f"| {r['block']} | {r['scene']} | {b.mmss(r['start'])} | {b.mmss(r['end'])} | {r['window']:.1f} s | {r['words']} | {r['wps']} | {r['speak_s']} s | {r['slack_s']} s |" for r in rows]
    L += ["", f"Total: {sum(r['words'] for r in rows)} words in {len(rows)} blocks.", "", "Spoken forms: " + "; ".join(f"{a} → “{c}”" for a, c in b.SPOKEN) + ".", "",
          "## Closing card", "", "- OCR (no contrast boost): " + ", ".join(f"“{k}” {'yes' if v else 'NO'}" for k, v in pv["closing_lines"].items()) + ".", "",
          "## Privacy", "",
          f"- {pv['frames']} frames (every 5 s) OCR'd: emails {len(pv['email'])}, hostnames/URLs {len(pv['host'])}, IPs {len(pv['ip'])}, secret/key/password patterns {len(pv['secret'])}. "
          f"Persona e-mails masked to “Demo persona” ({pv['persona']} occurrences).",
          "- SYNTHETIC banner on every app frame; synthetic fixture file names only. Mocked integrations appear only with their MOCK label; no live connector is shown.", "",
          "## No mobile / theme footage", "",
          f"- Single desktop viewport, no resizing or theme toggle. Minimum app-frame luminance YAVG {pv['min_luma']}; dark frames only at {pv['dark'][0]}–{pv['dark'][-1]} s (cards).", "",
          "## Publishing", "",
          "- Default: /demo-video and /api/v1/public/demo/ironvision_ai_rmf_demo.mp4 (this silent 3:45 cut).",
          "- Technical walkthrough (5 min): /api/v1/public/demo/ironvision_ai_rmf_technical_walkthrough.mp4, linked on /demo-video.",
          "- Archived (unlinked): the narrated 3:10 and earlier cuts under static/demo/archive/.", "",
          "## Reproduce", "",
          "`prep_v4.py` → `DEMO_SCENES=scenes_v4 DEMO_OUT=/tmp/demo_v4 record_demo.py` → `DEMO_OUT=/tmp/demo_v4 DEMO_MP4=/tmp/v4_raw.mp4 assemble.py` → `finish_v4.py` → "
          "`build_docs_v4.py` → `validate_v4.py` → `prep_v4.py --reset`."]
    (V.parent / "ironvision_ai_rmf_demo_validation.md").write_text("\n".join(L) + "\n")
    print("ok", len(L))


if __name__ == "__main__":
    main()
